import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const yaml = createRequire(join(repo, 'plugins/gamer-live/ui/package.json'))('js-yaml');
const work = join(repo, 'server/data/live-workflow-20261015/cleanup-20261015');
const sha = value => createHash('sha256').update(value).digest('hex');
const before = yaml.load(await readFile(join(work, 'backup/直播云游戏.before.yaml'), 'utf8'));
const primarySource = await readFile(join(work, '直播云游戏.yaml'), 'utf8');
const cleanupSource = await readFile(join(work, '直播云游戏收尾.yaml'), 'utf8');
const primary = yaml.load(primarySource);
const cleanup = yaml.load(cleanupSource);
const split = before.run.findIndex(step => 'reset_input' in step);
assert(split > 0);
assert.deepEqual(primary.run, before.run.slice(0, split), 'Preserve login, QR obstacles, daily/test arguments and failure notification');
assert.deepEqual(primary.params, before.params);
assert.deepEqual(primary.targets, before.targets);
assert.equal(primary.functions, undefined, 'No cleanup helper remains in the primary run');
assert.deepEqual(cleanup.functions, before.functions);
const expectedCleanup = structuredClone(before.run.slice(split));
expectedCleanup.at(-1).log = '退出账号确认已点击，本次直播收尾结束';
assert.deepEqual(cleanup.run, expectedCleanup, 'Keep reset/logout flow intact in its independent run');
assert.deepEqual(cleanup.run[0], { reset_input: {} }, 'Always reset before observing a page, even after primary failure');
assert(!cleanupSource.includes('notify:'), 'Cleanup cannot send a misleading daily failure notification');
assert(!cleanupSource.includes('云游戏日常.yaml'), 'Cleanup never repeats the daily');
const preparation = JSON.parse(await readFile(join(work, 'preparation.json'), 'utf8'));
assert.equal(sha(await readFile(join(repo, 'server/data/packages/hsr/plugins/gamer-yaml/automations/云游戏日常.yaml'))), preparation.daily_sha256);
const report = { passed: true, checks: 11, primary_sha256: sha(primarySource), cleanup_sha256: sha(cleanupSource), real_game: false, device_input: false };
await writeFile(join(work, 'scope-validation.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
